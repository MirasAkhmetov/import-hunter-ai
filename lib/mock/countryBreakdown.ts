function analysesToRawItems(): RawItem[] {
  return mockStore.analyses.getAll().flatMap((analysis) =>
    analysis.marketplaceResults.map((r) => ({
      id: r.id,
      title: r.title,
      marketplace: r.marketplace,
      country: r.country,
      purchasePriceKzt: r.profit.purchasePriceKzt,
      deliveryCostKzt: r.profit.deliveryCostKzt,
      netProfitKzt: r.profit.netProfitKzt,
      roiPercent: r.profit.roiPercent,
      riskScore: r.riskScore ?? 50,
      matchScore: r.matchScore ?? 70,
      manualStatus: "review",
      productTitle: analysis.productTitle,
    }))
  );
}

export function getMockCountryBreakdownData(): RawItem[] {
  const fromAnalyses = analysesToRawItems();
  if (fromAnalyses.length > 0) return fromAnalyses;
  return FALLBACK_ITEMS;
}
